// Regenerates src/lib/logo-data.ts from public/palletpoint-logo.jpg so the logo can be
// embedded in invoice PDFs without reading the filesystem at runtime.
//   node scripts/embed-logo.mjs
import { readFileSync, writeFileSync } from "node:fs";
const b64 = readFileSync("public/palletpoint-logo.jpg").toString("base64");
writeFileSync(
  "src/lib/logo-data.ts",
  `// GENERATED by scripts/embed-logo.mjs - do not edit by hand\nexport const LOGO_JPEG_BASE64 =\n  "${b64}";\n`
);
console.log("wrote src/lib/logo-data.ts", b64.length, "chars");
